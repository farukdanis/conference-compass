// Derives the analytics allow-list of session IDs (and dashboard titles) from public/program.json.
import fs from 'node:fs/promises';
const program=JSON.parse(await fs.readFile(new URL('../public/program.json',import.meta.url),'utf8'));
const rows=program.events.filter(e=>e.valid!==false);
const ids=rows.map(e=>e.id);
const titles=Object.fromEntries(rows.map(e=>[e.id,e.translations.en?.title||e.translations.tr?.title||e.id]));
await fs.writeFile(new URL('../worker/session-ids.js',import.meta.url),`// Generated by scripts/gen-session-ids.mjs from public/program.json. Do not edit by hand.\nexport const SESSION_IDS=${JSON.stringify(ids)};\nexport const SESSION_TITLES=${JSON.stringify(titles)};\n`);
console.log('session-ids.js:',ids.length,'sessions');
